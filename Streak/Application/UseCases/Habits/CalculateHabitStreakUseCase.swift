// Application/UseCases/Habits/CalculateHabitStreakUseCase.swift
// Per-habit streak and recent history, derived from the habit's generated tasks.
// Unscheduled weekdays, rest days and frozen days are skipped; today doesn't break
// the streak until it's over.

import Foundation

struct HabitDay: Equatable {
    enum State { case done, missed, pending, off }
    let date: Date
    let state: State
}

struct HabitProgress {
    let streak: Int
    let recent: [HabitDay]      // oldest → newest, ending today
}

struct CalculateHabitStreakUseCase {
    let settingsRepository: any SettingsRepository

    /// - Parameters:
    ///   - tasks: daily tasks generated by this habit (any dates).
    ///   - protectedDays: start-of-day dates whose overall status is rest or frozen.
    func execute(routine: HabitRoutine, tasks: [Task], protectedDays: Set<Date>, recentDays: Int = 14) -> HabitProgress {
        let cal = Calendar.current
        let today = cal.startOfDay(for: ActiveDayResolver.resolveActiveDate(for: Date(), settings: settingsRepository))
        let completedDays = Set(
            tasks.filter { $0.routineId == routine.id && !$0.isDeleted && $0.isCompleted }
                .map { cal.startOfDay(for: $0.targetDate) }
        )

        func state(on day: Date) -> HabitDay.State {
            if completedDays.contains(day) { return .done }
            guard routine.isInDateRange(day), routine.isScheduled(on: day) else { return .off }
            if protectedDays.contains(day) || ActiveDayResolver.isRestDay(day, settings: settingsRepository) { return .off }
            return day < today ? .missed : .pending
        }

        let recent: [HabitDay] = (0..<recentDays).reversed().compactMap { offset in
            cal.date(byAdding: .day, value: -offset, to: today).map { HabitDay(date: $0, state: state(on: $0)) }
        }

        var streak = 0
        var cursor = today
        let start = cal.startOfDay(for: routine.startDate)
        while cursor >= start {
            switch state(on: cursor) {
            case .done: streak += 1
            case .off, .pending: break
            case .missed: return HabitProgress(streak: streak, recent: recent)
            }
            guard let previous = cal.date(byAdding: .day, value: -1, to: cursor) else { break }
            cursor = previous
        }
        return HabitProgress(streak: streak, recent: recent)
    }
}
